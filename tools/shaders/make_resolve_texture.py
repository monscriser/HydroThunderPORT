"""Generate the ht_resolve_texture shaders from the ht_direct_resolve ones.

Each direct resolve shader writes the resolved words to the EDRAM-resolve
destination buffer (shared memory or the scaled resolve buffer). The variant
generated here does exactly the same and, in addition, writes the texel that
the texture load shader would later decode from that same word into the
texture that is about to be reloaded from it (ht_resolve_to_texture), so the
reload (texload) can be skipped. The texel = the load shader's endian swap of
the stored word, plus the depth conversion of the depth load shaders.

Texture texel coordinate = destination pixel coordinate + ht_tex_offset (the
position of the resolve destination base inside the texture, scaled; the CPU
checks the texture has the same pitch, and that the resolve either covers the
whole texture or the texture is up to date before it).
Push constants: ht_tex_info (offset 44): bits 0-1 texture endianness, bits 2-3
conversion (0 copy, 1 depth unorm, 2 depth float), bit 8 positive control
(texel x + 1, only for the proof mode); ht_tex_offset (offset 48): x | y << 16.

usage: python3 make_resolve_texture.py <ht_direct_resolve dir> <out dir>
"""
import re
import sys
from pathlib import Path

src = Path(sys.argv[1])
out = Path(sys.argv[2])
out.mkdir(parents=True, exist_ok=True)

HELPER = r"""
// ht: the texel the load shader would decode from a stored destination word.
uint ht_tex_texel(uint w)
{
    uint e = _3305.ht_tex_info & 3u;
    if (e == 1u || e == 2u) w = ((w & 16711935u) << 8u) | ((w & 4278255360u) >> 8u);
    if (e == 2u || e == 3u) w = (w << 16u) | (w >> 16u);
    uint conv = (_3305.ht_tex_info >> 2u) & 3u;
    if (conv == 1u)
    {
        uint d = w >> 8u;
        return floatBitsToUint(float(d + (d >> 23u)) * 5.9604644775390625e-08);
    }
    if (conv == 2u)
    {
        uint d = w >> 8u;
        uint m = d & 1048575u;
        uint ex = d >> 20u;
        bool den = ex == 0u;
        uint msb = uint(findMSB(m));
        uint r = ((mix(ex, msb + 4294967277u, den) + 112u) << 23u) |
                 (mix(m, (m << (20u - msb)) & 1048575u, den) << 3u);
        return d == 0u ? 0u : r;
    }
    return w;
}

void ht_tex_store(uvec2 p, uvec4 w)
{
    p += uvec2(_3305.ht_tex_offset & 65535u, _3305.ht_tex_offset >> 16u);
    if ((_3305.ht_tex_info & 256u) != 0u) p.x += 1u;
    ivec2 size = imageSize(ht_tex);
    if (p.y >= uint(size.y)) return;
    for (uint i = 0u; i < 4u; ++i)
    {
        if (p.x + i < uint(size.x))
            imageStore(ht_tex, ivec2(int(p.x + i), int(p.y)), uvec4(ht_tex_texel(w[i])));
    }
}
"""

count = 0
for f in sorted(src.glob("ht_direct_*_32bpp*.cs.glsl")):
    s = f.read_text()
    s = s.replace("// Generated by tools/shaders/make_direct_resolve.py",
                  "// Generated by tools/shaders/make_resolve_texture.py (from make_direct_resolve.py)", 1)
    assert s.count("layout(push_constant") == 1, f
    s = s.replace("layout(push_constant",
                  "layout(set = 2, binding = 0, r32ui) uniform writeonly uimage2D ht_tex;\n\nlayout(push_constant", 1)
    assert s.count("    uint ht_scale;\n") == 1, f
    s = s.replace("    uint ht_scale;\n", "    uint ht_scale;\n    uint ht_tex_info;\n    uint ht_tex_offset;\n", 1)
    assert s.count("\nvoid main()") == 1, f
    s = s.replace("\nvoid main()", HELPER + "\nvoid main()", 1)
    dest = re.findall(r"uvec2 (_\d+) = _\d+ \+ \(\(\(\(uvec2\(_3305\._m3\) >> uvec2\(20u, 24u\)\)", s)
    assert len(dest) == 1, (f, dest)
    d = dest[0]
    lines = s.split("\n")
    stores = 0
    res = []
    for line in lines:
        res.append(line)
        m = re.match(r"^(\s*)_5522\._m0\[.*\] = (_\d+);$", line)
        if m:
            res.append(f"{m.group(1)}ht_tex_store({d} + uvec2({4 * stores}u, 0u), {m.group(2)});")
            stores += 1
    full = "_full_" in f.name
    assert stores == (1 if full else 2), (f, stores)
    name = f.name.replace("ht_direct_", "ht_rtt_", 1)
    (out / name).write_text("\n".join(res))
    count += 1
print(f"generated {count}")
