"""Converts between the SDK's SPIR-V C headers and .spv files.

usage: spv_header.py extract <header.h> <out.spv>
       spv_header.py pack <in.spv> <header.h> <symbol>
"""
import re
import struct
import sys

if sys.argv[1] == "extract":
    text = open(sys.argv[2]).read()
    body = text[text.index("{") + 1:text.rindex("}")]
    words = [int(w, 16) for w in re.findall(r"0x[0-9A-Fa-f]+", body)]
    open(sys.argv[3], "wb").write(struct.pack(f"<{len(words)}I", *words))
    print("extraido", len(words), "palavras")
else:
    data = open(sys.argv[2], "rb").read()
    words = struct.unpack(f"<{len(data) // 4}I", data)
    lines = [", ".join(f"0x{w:08X}" for w in words[i:i + 6]) for i in range(0, len(words), 6)]
    out = ("// Generated by tools/shaders/spv_header.py (htrecomp, edge-protected RCAS).\n"
           f"const uint32_t {sys.argv[4]}[] = {{\n    " + ",\n    ".join(lines) + ",\n};\n")
    open(sys.argv[3], "w").write(out)
    print("gravado", len(words), "palavras em", sys.argv[3])
