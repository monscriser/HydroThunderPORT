"""Hydro Thunder port: build the "direct" texture load shaders (ht_texture_direct).

The SDK texture load shaders decode guest memory into a linear scratch buffer;
the texture cache then moved those bytes into the image (blit + image copy).
This takes the SDK's own SPIR-V, decompiled with spirv-cross (decompile_load.sh),
and only replaces the destination: every 16-byte store of 4 texels into the
scratch buffer becomes 4 imageStore()s into an r32ui storage view of the
texture itself. The decoding (tiling, resolution scale, endian, depth
conversion) is the untouched original code.

usage: python3 make_direct_load.py <dir with decompiled .comp> <out dir> name...
"""
import re
import sys
from pathlib import Path

src_dir, out_dir = Path(sys.argv[1]), Path(sys.argv[2])
out_dir.mkdir(parents=True, exist_ok=True)

for name in sys.argv[3:]:
    s = (src_dir / f"{name}.comp").read_text()
    # Destination buffer (set 0) -> storage image.
    m = re.search(r"layout\(set = 0, binding = 0, std430\) writeonly buffer \w+\s*\{\s*uvec4 _m0\[\];\s*\}\s*(\w+);", s)
    assert m, name
    dest = m.group(1)
    s = s.replace(m.group(0), "layout(set = 0, binding = 0, r32ui) uniform writeonly uimage2D ht_dest;")
    # Push constants: _m4 = size_blocks, _m5 = host_offset, _m6 = host_pitch.
    pc = re.search(r"layout\(push_constant, std430\) uniform \w+\s*\{[^}]*\}\s*(\w+);", s)
    assert pc, name
    c = pc.group(1)
    helper = f"""
// ht: one 16-byte scratch element = 4 consecutive 32-bit texels of a row.
void ht_store(uint element, uvec4 v)
{{
    uint byte_offset = element * 16u - {c}._m5;
    uint y = byte_offset / {c}._m6;
    uint x = (byte_offset - y * {c}._m6) >> 2u;
    if (y >= {c}._m4.y) return;
    if (x < {c}._m4.x) imageStore(ht_dest, ivec2(int(x), int(y)), uvec4(v.x));
    if (x + 1u < {c}._m4.x) imageStore(ht_dest, ivec2(int(x + 1u), int(y)), uvec4(v.y));
    if (x + 2u < {c}._m4.x) imageStore(ht_dest, ivec2(int(x + 2u), int(y)), uvec4(v.z));
    if (x + 3u < {c}._m4.x) imageStore(ht_dest, ivec2(int(x + 3u), int(y)), uvec4(v.w));
}}

void main()"""
    assert s.count("void main()") == 1
    s = s.replace("void main()", helper.lstrip("\n"), 1)
    stores = re.findall(rf"^(\s*){dest}\._m0\[(.+?)\] = (.+);$", s, flags=re.M)
    assert len(stores) == 2, (name, len(stores))
    s = re.sub(rf"^(\s*){dest}\._m0\[(.+?)\] = (.+);$", r"\1ht_store(\2, \3);", s, flags=re.M)
    assert dest + "." not in s, name
    header = ("// Generated by tools/shaders/make_direct_load.py from the SDK shader "
              f"{name} (spirv-cross). Do not edit.\n")
    (out_dir / f"ht_{name.replace('texture_load', 'texture_direct')}.cs.glsl").write_text(header + s)
    print("ok", name)
